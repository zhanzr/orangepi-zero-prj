#!/usr/bin/env python3
"""gen_stock_assets.py - regenerate the ILI9163C demo's stock assets from
the Orange Pi Zero board itself (Armbian):

  logo64.h          <- /boot/boot.bmp (Armbian boot logo, 320x240x24 BMP),
                       box-downscaled to the full 64x48, mono, light=lit
  ref/lcd_font_1608.c <- Lat15-Fixed16.psf.gz (the console font configured
                       in /etc/default/console-setup: Fixed 8x16), glyphs
                       0x20..0x7E, MSB-first -> LSB-first (bit 0 = leftmost)

The 6x12 info font (ASCII_1206_Table) is NOT regenerated: the Linux
console has no 6-pixel-wide stock font.

Usage (from WSL):  python3 tools/gen_stock_assets.py
Pulls the two files from the board via 'opz' ssh alias.
"""
import gzip
import io
import struct
import subprocess
import sys
import tempfile
import os

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)


def pull(board_path, local_path):
    subprocess.run(["scp", "-q", f"opz:{board_path}", local_path], check=True)


# ---------------- PSF font ----------------

def read_psf_glyphs(data):
    """Return list of 95 row-byte lists for chars 0x20..0x7E (8x16)."""
    if data[:2] == b"\x36\x04":  # PSF1
        mode, charsize = data[2], data[3]
        count = 512 if mode & 1 else 256
        offset = 4
        height, width = charsize, 8
    elif data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        (version, headersize, flags, length,
         charsize, height, width) = struct.unpack_from("<7I", data, 4)
        count, offset = length, headersize
    else:
        sys.exit("not a PSF1/PSF2 font")

    if (width, height) != (8, 16):
        sys.exit(f"unexpected glyph geometry {width}x{height}, want 8x16")
    print(f"PSF: {count} glyphs, {width}x{height}, {charsize} B/glyph")

    out = []
    for idx in range(0x20, 0x7F):
        rows = []
        if idx < count:
            base = offset + idx * charsize
            for r in range(16):
                raw = data[base + r]
                rows.append(int(format(raw, "08b")[::-1], 2))  # mirror
        else:
            rows = [0] * 16
        out.append(rows)
    return out


def emit_font(glyphs, path):
    with open(path, "w") as f:
        f.write("""/*
  lcd_font_1608.c - 8x16 ASCII font: the board's STOCK console font
  (Lat15-Fixed16, /usr/share/consolefonts, configured as FONTFACE="Fixed"
  FONTSIZE="8x16" in /etc/default/console-setup), regenerated by
  tools/gen_stock_assets.py. Glyphs 0x20..0x7E, 16 bytes each, one byte
  per row, bit 0 = leftmost pixel (LSB first), same convention as the
  6x12 vendor font. The 6x12 info font stays the vendor table: the Linux
  console has no 6-pixel-wide stock font.
*/
#include "lcd_font_1608.h"

const uint8_t asc2_1608[1520] = {
""")
        for g, rows in enumerate(glyphs):
            f.write("  /* %s */\n" % chr(0x20 + g))
            f.write("  " + ",".join("0x%02X" % b for b in rows) + ",\n")
        f.write("};\n\npFONT ASCII_Font16 = { asc2_1608, 8, 16, 16, 0 };\n")


# ---------------- BMP logo ----------------

def read_bmp_luma(data):
    if data[:2] != b"BM":
        sys.exit("not a BMP")
    off = struct.unpack_from("<I", data, 10)[0]
    w = struct.unpack_from("<i", data, 18)[0]
    h = struct.unpack_from("<i", data, 22)[0]
    bpp = struct.unpack_from("<H", data, 28)[0]
    if (w, h, bpp) != (320, 240, 24):
        sys.exit(f"unexpected BMP geometry {w}x{h}x{bpp}, want 320x240x24")
    rowsz = ((w * 3 + 3) // 4) * 4
    luma = [[0] * w for _ in range(h)]
    for y in range(h):  # positive height: bottom-up
        src = h - 1 - y
        base = off + src * rowsz
        for x in range(w):
            b, g, r = data[base + 3 * x: base + 3 * x + 3]
            luma[y][x] = (299 * r + 587 * g + 114 * b) // 1000
    return luma


def emit_logo(luma, threshold, path):
    w, h = 320, 240
    bw, bh = w // 64, h // 48  # 5x5 box downscale
    grid = [[0] * 64 for _ in range(48)]
    for gy in range(48):
        for gx in range(64):
            s = 0
            for dy in range(bh):
                for dx in range(bw):
                    s += luma[gy * bh + dy][gx * bw + dx]
            grid[gy][gx] = 1 if s / (bw * bh) >= threshold else 0

    # ascii preview for the operator
    for gy in range(0, 48, 2):
        print("".join("#" if grid[gy][gx] else "." for gx in range(64)))

    fb = bytearray(384)  # page-major: byte (y/8)*64+x, bit y%8
    for y in range(48):
        for x in range(64):
            if grid[y][x]:
                fb[(y // 8) * 64 + x] |= 1 << (y % 8)

    with open(path, "w") as f:
        f.write("""/* Auto-generated from the board's STOCK boot logo
 * (/boot/boot.bmp, the Armbian logo, 320x240x24 BMP), box-downscaled to
 * the full 64x48 panel, luminance threshold %d, light pixels -> lit.
 * Regenerated by tools/gen_stock_assets.py.
 * Layout: page-major, 64 cols x 48 rows, bit = row within page (LSB=top).
 */
#ifndef LOGO64_H
#define LOGO64_H

#define LOGO_W 64
#define LOGO_H 48

""" % threshold)
        f.write("const unsigned char logo64_fb[384] = {\n")
        for base in range(0, 384, 12):
            f.write("  " + ", ".join("0x%02X" % b for b in fb[base:base + 12]) + ",\n")
        f.write("};\n\n#endif /* LOGO64_H */\n")


def main():
    threshold = int(os.environ.get("LOGO_THRESHOLD", "40"))
    with tempfile.TemporaryDirectory() as tmp:
        bmp = os.path.join(tmp, "boot.bmp")
        psf = os.path.join(tmp, "font.psf")
        pull("/boot/boot.bmp", bmp)
        pull("/usr/share/consolefonts/Lat15-Fixed16.psf.gz", psf + ".gz")

        with gzip.open(psf + ".gz") as f:
            glyphs = read_psf_glyphs(f.read())
        emit_font(glyphs, os.path.join(APP, "ref", "lcd_font_1608.c"))

        with open(bmp, "rb") as f:
            luma = read_bmp_luma(f.read())
        emit_logo(luma, threshold, os.path.join(APP, "logo64.h"))
    print("regenerated: logo64.h + ref/lcd_font_1608.c")


if __name__ == "__main__":
    main()
